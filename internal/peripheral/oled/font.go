// glyphIndex は文字からグリフ配列のインデックスを返します。
// 'L' → 0, '0'〜'3' → 1〜4。未定義文字は -1 を返します。
func glyphIndex(c byte) int {
	switch c {
	case 'L':
		return 0
	case '0':
		return 1
	case '1':
		return 2
	case '2':
		return 3
	case '3':
		return 4
	default:
		return -1
	}
}
